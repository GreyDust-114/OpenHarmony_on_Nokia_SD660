"""Generate byte-exact FT8716U command arrays from the public B2N vendor DTS.

The input is a public source snapshot, not a dump of a user's phone. Output
retains every Qualcomm 7-byte command header and payload including padding.
"""
import argparse
import hashlib
from pathlib import Path
import re


def command_bytes(source, name):
    clean = re.sub(r'/\*.*?\*/|//[^\n]*', '', source, flags=re.S)
    match = re.search(re.escape(name) + r'\s*=\s*\[([^]]+)\]', clean)
    if not match:
        raise ValueError('Missing command property: ' + name)
    data = bytes.fromhex(match[1])
    offset = 0
    while offset < len(data):
        if len(data) - offset < 7:
            raise ValueError('Truncated header')
        dtype, last, channel, ack, delay, hi, lo = data[offset:offset+7]
        size = hi * 256 + lo
        if dtype not in (0x05, 0x15, 0x39) or last != 1 or channel != 0 or ack != 0:
            raise ValueError('Unsupported command header')
        if not size or offset + 7 + size > len(data):
            raise ValueError('Truncated payload')
        offset += 7 + size
    return data


def render(source):
    lines = ['/* SPDX-License-Identifier: GPL-2.0-only */',
             '/* B2N vendor command stream; Copyright (c) 2013 The Linux Foundation. */',
             '/* Generated by generate_b2n_panel_commands.py; preserve types and padding. */',
             '#ifndef B2N_FT8716U_COMMANDS_H', '#define B2N_FT8716U_COMMANDS_H', '']
    for kind in ('on', 'off'):
        data = command_bytes(source, 'qcom,mdss-dsi-' + kind + '-command')
        lines.append('/* Stream SHA256: ' + hashlib.sha256(data).hexdigest() + ' */')
        lines.append('static const u8 b2n_' + kind + '_commands[] = {')
        pos = 0
        while pos < len(data):
            size = int.from_bytes(data[pos+5:pos+7], 'big')
            packet = data[pos:pos+7+size]
            lines.append('\t' + ', '.join(f'0x{v:02x}' for v in packet) + ',')
            pos += 7 + size
        lines.extend(['};', ''])
    return '\n'.join(lines + ['#endif', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    args.output.write_text(render(args.source.read_text()), encoding='utf-8', newline='\n')
